import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
import {buildDdiPeriodProducts} from '../../gravity-app/src/domain/quarterProfiles.js';
import {displayProductName} from '../../gravity-app/src/domain/report.js';

const root = new URL('../../', import.meta.url), dir = new URL('.', import.meta.url).pathname;
const read = async p => JSON.parse(await fs.readFile(new URL(p, root),'utf8'));
const source = await read('gravity-app/public/report-data.json');
const app = await fs.readFile(new URL('gravity-app/src/app/App.jsx',root),'utf8');
const imports = new Map([...app.matchAll(/import (\w+) from '\.\.\/data\/([^']+\.json)'/g)].map(m=>[m[1],m[2]]));
const overlays = await Promise.all(app.match(/const Q3_OVERLAYS = \[([^\]]+)\]/)[1].split(',').map(k=>read('gravity-app/src/data/'+imports.get(k.trim()))));
const args = await Promise.all(['salary-products','reporting-regularity-missing','funnel-action-missing'].map(n=>read(`gravity-app/src/data/${n}-q3-2026.json`)));
const products = buildDdiPeriodProducts(source.products,'III кв. 2026',overlays,...args,await read('gravity-app/public/backlog-data.json'));
const code = 'mehaniki.doprodazhi_up_sell';
const categories = ['100%','Частично','0%','Не применимо','Нет метрики','Нет оценки'];
const counts = Object.fromEntries(categories.map(c=>[c,0]));
assert.equal(products.length,76); assert.equal(new Set(products.map(p=>p.id)).size,76);
const rows = products.sort((a,b)=>`${a.unit} ${a.name}`.localeCompare(`${b.unit} ${b.name}`,'ru')).map(p=>{
  const candidates = p.metrics.flatMap(b=>b.metrics || []).filter(m=>m.code===code);
  assert.ok(candidates.length<=1, `${p.name}: duplicate up-sell`);
  const m = candidates[0]; let score=null, status;
  if (!m) status='Нет метрики';
  else if (m.is_applicabble_flg===false || !(m.max_value>0)) status='Не применимо';
  else if (!Number.isFinite(m.value)) status='Нет оценки';
  else {
    score=m.value/m.max_value; assert.ok(score>=0 && score<=1+1e-9,p.name);
    status=Math.abs(score-1)<1e-9?'100%':score===0?'0%':'Частично';
  }
  counts[status]++;
  return [p.unit,displayProductName(p.name),score===null?status:score,m?.value??null,m?.max_value??null,status];
});
assert.equal(Object.values(counts).reduce((s,v)=>s+v,0),76);
assert.equal(rows.find(r=>r[1]==='Интернет-Эквайринг')[5],'Не применимо');
const commit=execFileSync('git',['rev-parse','--short','HEAD'],{cwd:root}).toString().trim();
await fs.writeFile(dir+'snapshot.json',JSON.stringify({period:'III кв. 2026',commit,code,counts,rows},null,2));
console.log(JSON.stringify(counts));

const wb=Workbook.create(), sheet=wb.worksheets.add('Up-sell');
const last=rows.length+7;
sheet.showGridLines=false; sheet.tabColor='#454545';
sheet.getRange(`A1:F${last}`).format.font={name:'Arial',size:10,color:'#242424'};
sheet.getRange(`A1:F${last}`).format.verticalAlignment='center';
sheet.getRange('A2').values=[['Up-sell — III квартал 2026']];
sheet.getRange('A2').format.font={name:'Arial',size:14,bold:true,color:'#242424'};
sheet.getRange('A3').values=[[`Источник: расчёт DDI и подтверждённые корректировки, версия ${commit}, 06.11.2026. 76 команд.`]];
sheet.getRange('A3').format.font={name:'Arial',size:10,italic:true,color:'#666666'};
sheet.getRange('A4:F4').values=[categories];
sheet.getRange('A4:F4').format={fill:'#EEEEEE',font:{name:'Arial',size:10,bold:true,color:'#333333'},horizontalAlignment:'center',rowHeight:25};
sheet.getRange('A5:F5').formulas=[categories.map((_,i)=>`=COUNTIFS($F$8:$F$${last},${String.fromCharCode(65+i)}4)`)];
sheet.getRange('A5:F5').format.horizontalAlignment='center';
sheet.getRange('A5:F5').setNumberFormat('#,##0');
sheet.getRange('A7:F7').values=[['Юнит','Команда','Оценка Up-sell','Балл','Максимум','Статус']];
sheet.getRange(`A8:F${last}`).values=rows;
sheet.getRange(`A8:F${last}`).format.rowHeight=30;
sheet.getRange(`B8:B${last}`).format.wrapText=true;
sheet.getRange(`C8:C${last}`).setNumberFormat('0.0%');
sheet.getRange(`D8:E${last}`).setNumberFormat('0.00');
sheet.getRange(`C8:E${last}`).format.horizontalAlignment='right';
const table=sheet.tables.add(`A7:F${last}`,true,'UpsellScores');
table.style='TableStyleMedium1'; table.showBandedRows=false; table.showFilterButton=true;
sheet.getRange('A7:F7').format={fill:'#3F3F3F',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},wrapText:true,horizontalAlignment:'center',verticalAlignment:'center',rowHeight:32};
[20,58,22,18,18,22].forEach((w,i)=>sheet.getRange(`${String.fromCharCode(65+i)}4:${String.fromCharCode(65+i)}${last}`).format.columnWidth=w);
sheet.freezePanes.freezeRows(7);
wb.recalculate();
assert.deepEqual(sheet.getRange('A5:F5').values,[categories.map(c=>counts[c])]);
const index=rows.findIndex(r=>r[5]==='100%'); assert.ok(index>=0);
sheet.getRange(`F${index+8}`).values=[['0%']]; wb.recalculate();
assert.equal(sheet.getRange('A5').values[0][0],counts['100%']-1);
assert.equal(sheet.getRange('C5').values[0][0],counts['0%']+1);
sheet.getRange(`F${index+8}`).values=[['100%']]; wb.recalculate();
assert.deepEqual(sheet.getRange('A5:F5').values,[categories.map(c=>counts[c])]);
await fs.writeFile(dir+'inspection.ndjson',(await wb.inspect({kind:'table',range:'Up-sell!A4:F16',include:'values,formulas',tableMaxRows:13,tableMaxCols:6})).ndjson);
await fs.writeFile(dir+'errors.ndjson',(await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#NULL!',options:{useRegex:true,maxResults:20}})).ndjson);
const preview=await wb.render({sheetName:'Up-sell',range:'A1:F20',scale:1.5,format:'png'});
await fs.writeFile(dir+'preview.png',new Uint8Array(await preview.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(dir+'DDI_Up-sell_III_квартал_2026.xlsx');
