// Та же сортировка, что compareNames в DDI Catalog.jsx.
const nameCollator = new Intl.Collator('en', {sensitivity: 'base', numeric: true});

const translit = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};
const compactSearch = value => String(value).toLocaleLowerCase('ru-RU').replaceAll('ё', 'е').replace(/[^a-zа-я0-9]/g, '');
const romanize = (value, simple = false) => [...String(value).toLocaleLowerCase('ru-RU')]
  .map(char => simple ? ({ё: 'e', х: 'h', ц: 'c', щ: 'sch'}[char] ?? translit[char] ?? char) : (translit[char] ?? char))
  .join('').replace(/[^a-z0-9]/g, '');

export function filterTeamOption(option, filter) {
  const query = compactSearch(filter);
  if (!query) return true;
  const name = option.text || option.content || option.value || '';
  return [compactSearch(name), romanize(name), romanize(name, true)]
    .some(candidate => candidate.includes(query));
}

