export function otherTeamSections(profile, shared = {}) {
  const metrics = ['DP', 'PC'].includes(profile.unit) ? [] : metricQuestions(profile);
  const sections = [shared.intro, {id: 'metrics', title: 'Ключевые метрики', description: profile.type === 'Сегмент' ? 'Клиентская база сегмента и инструменты мониторинга.' : 'Метрики канала и инструменты мониторинга.', questions: metrics}, ...dataSections(profile)];
  if (profile.sheet === 'Кампейнинг') sections.push(...campaignSections(profile));
  else sections.push(...funnelSpecs(profile).map(spec => funnelSection(profile, spec)), alertsSection(profile), mechanicsSection(profile));
  if (has(profile, 'hyp.discovery_40_backlog') && shared.discovery) {
    const row = profile.type === 'Сегмент' ? 196 : profile.unit === 'PC' ? 139 : profile.unit === 'DP' ? 167 : profile.sheet === 'Data' ? 187 : 92;
    const sourceQuestions = shared.discovery.questions || [shared.discovery];
    sections.push({id: 'research', title: 'Исследования', description: 'Доля исследовательских задач в бэклоге.', questions: sourceQuestions.filter(q => q.id === 'discovery').map(q => ({...q, sheet: profile.sheet, row, metricCode: 'hyp.discovery_40_backlog', scoreKind: 'discovery', title: 'Какая доля задач аналитиков данных (DA) в бэклоге связана с исследованиями?', ...(q.inlineProof ? {inlineProof: {...q.inlineProof, sheet: profile.sheet, row: row + 6}} : {})}))});
  }
  if (shared.support) sections.push(shared.support.questions ? shared.support : {id: 'support', title: 'Поддержка', description: '', questions: [shared.support]});
  return sections.filter(section => section && section.questions?.length);
}
